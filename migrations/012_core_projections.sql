CREATE TABLE core.account (
  org_id uuid NOT NULL REFERENCES core.org(org_id),
  account_id uuid,
  display_name text,
  institution_name text,
  mask text,
  kind text CHECK (kind IN ('checking','savings','money_market','credit_card','line_of_credit','loan','mortgage','brokerage','other')),
  balance_orientation text CHECK (balance_orientation IN ('asset','liability')),
  verification_method text CHECK (verification_method IN ('cash_statement','card_statement','loan_principal','unverified')),
  currency char(3),
  status text CHECK (status IN ('active','missing','closed','placeholder')),
  missing_since timestamptz,
  closed_at timestamptz,
  closed_evidence jsonb,
  required_start_date date,
  observed_start_date date,
  history_state text CHECK (history_state IN ('unknown','loading','complete','partial')),
  coverage_gap text,
  PRIMARY KEY (account_id),
  UNIQUE (org_id, account_id),
  FOREIGN KEY (org_id, account_id) REFERENCES core.account_allocation (org_id, account_id)
);
CREATE TABLE core.account_assignment (
  org_id uuid NOT NULL REFERENCES core.org(org_id),
  id uuid DEFAULT gen_random_uuid(),
  source_account_id uuid NOT NULL,
  account_id uuid NOT NULL,
  valid tstzrange NOT NULL,
  reason text NOT NULL CHECK (reason IN ('placeholder','first_seen','relink','ruling')),
  ruled_by text,
  publication_id bigint NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (org_id, id),
  FOREIGN KEY (org_id, source_account_id) REFERENCES core.source_account (org_id, source_account_id),
  FOREIGN KEY (org_id, account_id) REFERENCES core.account (org_id, account_id),
  EXCLUDE USING gist (source_account_id WITH =, valid WITH &&)
);
CREATE TABLE core.transaction (
  org_id uuid NOT NULL REFERENCES core.org(org_id),
  transaction_id uuid,
  source_account_id uuid NOT NULL,
  account_id uuid NOT NULL,
  amount numeric(14,2),
  currency char(3),
  posted_date date,
  authorized_date date,
  datetime timestamptz,
  pending bool,
  description_raw text,
  original_description text,
  merchant_name text,
  merchant_entity_id text,
  pfc_primary text,
  pfc_detailed text,
  pfc_confidence text,
  pfc_version text,
  payment_channel text,
  check_number text,
  counterparties jsonb,
  location jsonb,
  payment_meta jsonb,
  status text CHECK (status IN ('active','removed','quarantined')),
  removed_at timestamptz,
  revision int NOT NULL,
  revision_publication_id bigint NOT NULL,
  authoritative_connection_id uuid,
  authoritative_external_id text,
  PRIMARY KEY (transaction_id),
  UNIQUE (org_id, transaction_id),
  FOREIGN KEY (org_id, transaction_id) REFERENCES core.identity_allocation (org_id, transaction_id),
  FOREIGN KEY (org_id, source_account_id) REFERENCES core.source_account (org_id, source_account_id),
  FOREIGN KEY (org_id, account_id) REFERENCES core.account (org_id, account_id),
  FOREIGN KEY (org_id, authoritative_connection_id) REFERENCES core.source_connection (org_id, connection_id)
);
CREATE TABLE core.transaction_alias (
  org_id uuid NOT NULL REFERENCES core.org(org_id),
  connection_id uuid,
  external_id text,
  transaction_id uuid NOT NULL,
  role text CHECK (role IN ('pending','posted','other')),
  authoritative bool NOT NULL,
  state text CHECK (state IN ('active','removed','superseded')),
  first_seen_publication_id bigint NOT NULL,
  last_seen_publication_id bigint NOT NULL,
  PRIMARY KEY (connection_id, external_id),
  UNIQUE (org_id, connection_id, external_id),
  FOREIGN KEY (org_id, connection_id) REFERENCES core.source_connection (org_id, connection_id),
  FOREIGN KEY (org_id, transaction_id) REFERENCES core.transaction (org_id, transaction_id)
);
CREATE UNIQUE INDEX one_authoritative_alias ON core.transaction_alias (transaction_id) WHERE authoritative;
CREATE TABLE core.transaction_revision (
  org_id uuid NOT NULL REFERENCES core.org(org_id),
  transaction_id uuid,
  revision int,
  publication_id bigint NOT NULL,
  position int NOT NULL,
  cause text CHECK (cause IN ('added','modified','removed','reactivated','pending_claimed','currency_quarantine','currency_restored','reassigned','relink_merged')),
  source_api_call_id bigint,
  source_connection_id uuid NOT NULL,
  source_external_id text NOT NULL,
  predecessor_revision int,
  projection_version int NOT NULL,
  PRIMARY KEY (transaction_id, revision),
  UNIQUE (org_id, transaction_id, revision),
  FOREIGN KEY (org_id, transaction_id) REFERENCES core.transaction (org_id, transaction_id),
  FOREIGN KEY (org_id, source_api_call_id) REFERENCES raw.api_call (org_id, id),
  FOREIGN KEY (org_id, source_connection_id) REFERENCES core.source_connection (org_id, connection_id)
);
CREATE TABLE core.balance_observation (
  org_id uuid NOT NULL REFERENCES core.org(org_id),
  id uuid DEFAULT gen_random_uuid(),
  source_account_id uuid NOT NULL,
  account_id uuid NOT NULL,
  publication_id bigint NOT NULL,
  observed_at timestamptz NOT NULL,
  provider_as_of timestamptz,
  current numeric(14,2),
  available numeric(14,2),
  limit_amount numeric(14,2),
  currency char(3),
  source text CHECK (source IN ('sync_page','accounts_get','balance_get')),
  api_call_id bigint NOT NULL,
  PRIMARY KEY (id),
  UNIQUE (org_id, id),
  FOREIGN KEY (org_id, source_account_id) REFERENCES core.source_account (org_id, source_account_id),
  FOREIGN KEY (org_id, account_id) REFERENCES core.account (org_id, account_id),
  FOREIGN KEY (org_id, api_call_id) REFERENCES raw.api_call (org_id, id),
  UNIQUE (source_account_id, publication_id, source)
);
CREATE TABLE core.quarantine (
  org_id uuid NOT NULL REFERENCES core.org(org_id),
  id uuid DEFAULT gen_random_uuid(),
  kind text CHECK (kind IN ('currency','relink_overlap','duplicate_claim','unknown_modified','unknown_removed','competing_claim','invalid_precision')),
  connection_id uuid NOT NULL,
  external_id text NOT NULL,
  api_call_id bigint,
  raised_publication_id bigint NOT NULL,
  payload jsonb,
  resolved_by_decision_id uuid,
  PRIMARY KEY (id),
  UNIQUE (org_id, id),
  FOREIGN KEY (org_id, connection_id) REFERENCES core.source_connection (org_id, connection_id),
  FOREIGN KEY (org_id, api_call_id) REFERENCES raw.api_call (org_id, id),
  FOREIGN KEY (org_id, resolved_by_decision_id) REFERENCES core.identity_decision (org_id, id),
  UNIQUE (kind, connection_id, external_id, raised_publication_id)
);
