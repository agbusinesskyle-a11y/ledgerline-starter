CREATE ROLE ll_owner NOLOGIN;
CREATE ROLE ll_sync NOLOGIN;
CREATE ROLE ll_app NOLOGIN;
CREATE ROLE ll_verify NOLOGIN;
CREATE ROLE ll_rebuild NOLOGIN;
CREATE ROLE ll_backup NOLOGIN;
CREATE ROLE ll_reader NOLOGIN;
CREATE EXTENSION btree_gist;
CREATE EXTENSION pgcrypto;
CREATE SCHEMA core AUTHORIZATION ll_owner;
CREATE SCHEMA raw AUTHORIZATION ll_owner;
CREATE SCHEMA verify AUTHORIZATION ll_owner;
CREATE SCHEMA ops AUTHORIZATION ll_owner;
CREATE SCHEMA serve AUTHORIZATION ll_owner;
-- meta.migration and meta are the migrator's only bootstrap objects.
ALTER SCHEMA meta OWNER TO ll_owner;
ALTER TABLE meta.migration OWNER TO ll_owner;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
SET LOCAL ROLE ll_owner;
CREATE FUNCTION meta.immutable_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  RAISE EXCEPTION 'IMMUTABLE_ROW' USING ERRCODE = 'P0001';
END;
$$;
REVOKE ALL ON FUNCTION meta.immutable_guard() FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE ll_owner IN SCHEMA core REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE ll_owner IN SCHEMA raw REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE ll_owner IN SCHEMA verify REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE ll_owner IN SCHEMA ops REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE ll_owner IN SCHEMA serve REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
ALTER DEFAULT PRIVILEGES FOR ROLE ll_owner IN SCHEMA meta REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
