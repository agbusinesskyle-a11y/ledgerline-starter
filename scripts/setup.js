#!/usr/bin/env node
// One-time local setup: writes YOUR OWN freshly generated secrets into `.env`
// (and a backup key + a "save these" note into `.secrets/`). It never overwrites
// an existing file. Nothing here talks to Plaid, Railway or any other service.
//
//   node scripts/setup.js                      # interactive: asks for an app password
//   node scripts/setup.js --non-interactive    # generates a random app password instead
//   options: --env-file PATH   (default .env)
//            --secrets-dir DIR (default .secrets)
//            --admin-url URL   (local Postgres admin URL written into .env)
import { randomBytes } from 'node:crypto';
import { mkdir, writeFile, access } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { createInterface } from 'node:readline/promises';
import bcrypt from 'bcryptjs';
import * as OTPAuth from 'otpauth';
import { generateIdentity, identityToRecipient } from 'age-encryption';

const args = process.argv.slice(2);
const opt = (name, fallback) => { const i = args.indexOf(name); return i >= 0 && args[i + 1] ? args[i + 1] : fallback; };
const nonInteractive = args.includes('--non-interactive') || !process.stdin.isTTY;
const envFile = resolve(opt('--env-file', '.env'));
const secretsDir = resolve(opt('--secrets-dir', '.secrets'));
const adminUrl = opt('--admin-url', 'postgres://postgres@127.0.0.1:5432/ledgerline');

const exists = async path => access(path).then(() => true, () => false);
const random = (bytes = 32) => randomBytes(bytes).toString('base64');
// Role passwords go inside postgres:// URLs, so keep them URL-safe.
const rolePassword = () => randomBytes(24).toString('base64url');

async function main() {
  for (const path of [envFile, join(secretsDir, 'backup.age.key'), join(secretsDir, 'SAVE-THESE-THEN-DELETE.txt')]) {
    if (await exists(path)) {
      console.error(`refusing to overwrite ${path} — it already exists. Move it away first if you really want new secrets.`);
      process.exit(1);
    }
  }

  let password;
  if (nonInteractive) password = randomBytes(18).toString('base64url');
  else {
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    password = (await rl.question('Choose a password for the ledgerline web page (leave blank to generate one): ')).trim();
    rl.close();
    if (!password) password = randomBytes(18).toString('base64url');
  }
  if (Buffer.byteLength(password) > 72) { console.error('password must be at most 72 bytes'); process.exit(1); }

  const totp = new OTPAuth.TOTP({ issuer: 'ledgerline', label: 'operator', algorithm: 'SHA1', digits: 6, period: 30,
    secret: new OTPAuth.Secret({ size: 20 }) });
  const identity = await generateIdentity();
  const recipient = await identityToRecipient(identity);
  const roles = ['SYNC', 'APP', 'VERIFY', 'BACKUP', 'READER', 'REBUILD'];
  const rolePasswords = Object.fromEntries(roles.map(r => [r, rolePassword()]));

  const env = `# ledgerline local settings — generated by scripts/setup.js on ${new Date().toISOString().slice(0, 10)}.
# NEVER commit this file. See .env.example for what every variable means.

# --- Local database (edit LOCAL_PG_ADMIN_URL to match your Postgres) ---
# A superuser/admin URL to the (empty) database ledgerline should live in.
LOCAL_PG_ADMIN_URL=${adminUrl}

# --- Database role passwords (generated; the migrator sets them) ---
${roles.map(r => `ROLE_PASSWORD_LL_${r}=${rolePasswords[r]}`).join('\n')}

# --- Encryption + web login (generated) ---
TOKEN_KEK=${random(32)}
APP_SESSION_SECRET=${random(32)}
APP_TOTP_SECRET=${totp.secret.base32}
APP_LOGIN_PASSWORD_HASH=${await bcrypt.hash(password, 12)}

# --- Plaid: copy these from YOUR Plaid dashboard (https://dashboard.plaid.com → Developers → Keys) ---
PLAID_CLIENT_ID=
PLAID_SECRET=
# sandbox first (fake banks, free). Switch to production only with production keys.
PLAID_ENV=sandbox
PLAID_PRODUCTS=transactions
# Must also be added in the Plaid dashboard under Developers → API → Allowed redirect URIs.
LINK_REDIRECT_URI=http://localhost:3000/link/oauth

# --- General ---
LL_ORG_SLUG=main
PORT=3000

# --- Backups (optional locally; needed on Railway) ---
BACKUP_AGE_RECIPIENT=${recipient}
BACKUP_S3_BUCKET=
BACKUP_PREFIX=ledgerline/
BACKUP_S3_ENDPOINT=
BACKUP_S3_ACCESS_KEY_ID=
BACKUP_S3_SECRET_ACCESS_KEY=

# --- Alerts (optional) ---
TWILIO_ACCOUNT_SID=
TWILIO_AUTH_TOKEN=
TWILIO_FROM=
TWILIO_ALERT_TO=
HEALTHCHECKS_PING_SYNC=
HEALTHCHECKS_PING_COVERAGE=
HEALTHCHECKS_PING_ALERTS=
HEALTHCHECKS_PING_BACKUP=
`;

  await mkdir(secretsDir, { recursive: true, mode: 0o700 });
  await writeFile(join(secretsDir, 'backup.age.key'), `${identity}\n`, { mode: 0o600, flag: 'wx' });
  await writeFile(join(secretsDir, 'SAVE-THESE-THEN-DELETE.txt'), `Put these in your password manager, then delete this file.

ledgerline web page password: ${password}

Two-factor code: add this to an authenticator app (Google Authenticator, 1Password, Authy...).
Most apps let you paste it as a "setup key":  ${totp.secret.base32}
or import this link:  ${totp.toString()}

Backup decryption key: the file backup.age.key next to this note. Keep a copy somewhere safe
OFFLINE (password manager attachment). Without it, backups cannot be restored. Never upload it to Railway.

Also save a copy of the whole .env file in your password manager: if TOKEN_KEK is lost,
every connected bank must be reconnected.
`, { mode: 0o600, flag: 'wx' });
  await writeFile(envFile, env, { mode: 0o600, flag: 'wx' });

  console.log(`Wrote ${envFile}`);
  console.log(`Wrote ${join(secretsDir, 'backup.age.key')} and ${join(secretsDir, 'SAVE-THESE-THEN-DELETE.txt')}`);
  console.log(`
Next:
  1. Open ${join(secretsDir, 'SAVE-THESE-THEN-DELETE.txt')}, save its contents in your password manager.
  2. From YOUR Plaid dashboard (https://dashboard.plaid.com):
       - Developers → Keys: copy "client_id" into PLAID_CLIENT_ID and the Sandbox "secret" into PLAID_SECRET.
       - Developers → API → Allowed redirect URIs: add ${'http://localhost:3000/link/oauth'}
  3. Check LOCAL_PG_ADMIN_URL in .env points at your Postgres, then: npm run local -- migrate`);
}

main().catch(error => { console.error(`setup failed: ${error.message}`); process.exit(1); });
